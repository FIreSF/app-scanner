#!/usr/bin/env python3
"""
Writeup index builder (spec §11 `/update` pipeline, final stage).

The ingestion pipeline is:

    fetch -> writeups/raw/ -> human/agent processing -> writeups/processed/ -> index

This script implements the last, deterministic stage: it rebuilds
`writeups/index.md` from the processed writeups so `orchestrator-agent` can run
similar-case expansion without guessing file names.

Front matter is optional; a YAML subset is parsed (flat `key: value` pairs and
inline `[a, b]` lists).  Files without front matter fall back to the first
markdown heading.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from typing import Any, Dict, List, Optional, Sequence

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
WRITEUPS_DIR = os.path.join(ROOT_DIR, "writeups")
PROCESSED_DIR = os.path.join(WRITEUPS_DIR, "processed")
RAW_DIR = os.path.join(WRITEUPS_DIR, "raw")
INDEX_PATH = os.path.join(WRITEUPS_DIR, "index.md")

FRONT_MATTER_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.DOTALL)
HEADING_RE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
LIST_RE = re.compile(r"^\[(.*)\]$")


def _parse_scalar(value: str) -> Any:
    value = value.strip().strip('"').strip("'")
    match = LIST_RE.match(value)
    if match:
        inner = match.group(1).strip()
        if not inner:
            return []
        return [item.strip().strip('"').strip("'") for item in inner.split(",")]
    return value


def parse_writeup(path: str, root_dir: str = ROOT_DIR) -> Dict[str, Any]:
    """Extract metadata from a processed writeup."""
    with open(path, "r", encoding="utf-8-sig") as handle:
        content = handle.read()

    metadata: Dict[str, Any] = {}
    match = FRONT_MATTER_RE.match(content)
    body = content
    if match:
        body = content[match.end():]
        for line in match.group(1).splitlines():
            if ":" not in line or line.strip().startswith("#"):
                continue
            key, value = line.split(":", 1)
            metadata[key.strip().lower()] = _parse_scalar(value)

    heading = HEADING_RE.search(body)
    title = metadata.get("title") or (heading.group(1).strip() if heading else os.path.splitext(os.path.basename(path))[0])

    return {
        "path": os.path.relpath(path, root_dir).replace("\\", "/"),
        "title": str(title),
        "vuln_class": str(metadata.get("vuln_class") or metadata.get("class") or "uncategorised"),
        "source": str(metadata.get("source") or "unknown"),
        "tags": metadata.get("tags") or [],
        "has_front_matter": bool(match),
    }


def collect_writeups(
    processed_dir: str = PROCESSED_DIR,
    raw_dir: str = RAW_DIR,
    root_dir: str = ROOT_DIR,
) -> Dict[str, Any]:
    processed: List[Dict[str, Any]] = []
    if os.path.isdir(processed_dir):
        for current, _dirs, files in os.walk(processed_dir):
            for name in sorted(files):
                if name.lower().endswith(".md"):
                    processed.append(parse_writeup(os.path.join(current, name), root_dir))

    raw: List[str] = []
    if os.path.isdir(raw_dir):
        for current, _dirs, files in os.walk(raw_dir):
            for name in sorted(files):
                if not name.startswith("."):
                    raw.append(os.path.relpath(os.path.join(current, name), root_dir).replace("\\", "/"))

    processed.sort(key=lambda item: (item["vuln_class"], item["title"].lower()))
    return {"processed": processed, "raw": raw}


def render_index(data: Dict[str, Any]) -> str:
    lines = [
        "# Writeup Index",
        "",
        "> Generated by `python scripts/writeup_index.py`. Do not edit by hand.",
        "",
        f"- **Processed writeups:** {len(data['processed'])}",
        f"- **Raw / unprocessed files:** {len(data['raw'])}",
        "",
    ]

    if data["processed"]:
        lines += ["| Title | Vuln class | Source | File |", "|---|---|---|---|"]
        for item in data["processed"]:
            lines.append(
                f"| {item['title']} | {item['vuln_class']} | {item['source']} | `{item['path']}` |"
            )
    else:
        lines.append("_No processed writeups yet. Drop source material in `writeups/raw/`, process it, "
                     "then move the result to `writeups/processed/` and re-run the indexer._")

    if data["raw"]:
        lines += ["", "## Pending raw material", ""]
        for path in data["raw"]:
            lines.append(f"- `{path}`")

    lines += [
        "",
        "## Usage",
        "",
        "1. `writeups/raw/` — fetched source material (never edited in place).",
        "2. `writeups/processed/` — normalised writeups with optional front matter:",
        "",
        "```markdown",
        "---",
        "title: Intent redirection to unexported activity",
        "vuln_class: platform",
        "source: hackerone",
        "tags: [android, intent, ipc]",
        "---",
        "```",
        "",
        "3. Run `python scripts/writeup_index.py` after each batch.",
        "4. `orchestrator-agent` uses this index for similar-case expansion before final judgement.",
    ]
    return "\n".join(lines) + "\n"


def write_index(data: Dict[str, Any], path: str = INDEX_PATH) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_index(data))
    return path


def read_text(path: str) -> str:
    with open(path, "r", encoding="utf-8-sig") as handle:
        return handle.read()


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Rebuild the writeup index")
    parser.add_argument("--json", action="store_true", help="Print metadata instead of writing the index")
    parser.add_argument("--check", action="store_true", help="Fail if the index is out of date")
    args = parser.parse_args(argv)

    data = collect_writeups()

    if args.json:
        print(json.dumps(data, indent=2))
        return 0

    if args.check:
        if not os.path.isfile(INDEX_PATH):
            print("[-] writeups/index.md is missing; run: python scripts/writeup_index.py")
            return 1
        expected = render_index(data)
        if read_text(INDEX_PATH) != expected:
            print("[-] writeups/index.md is out of date; run: python scripts/writeup_index.py")
            return 1
        print("[+] writeups/index.md is up to date")
        return 0

    path = write_index(data)
    print(f"[+] Index rebuilt: {path}")
    print(f"    Processed: {len(data['processed'])} | Raw pending: {len(data['raw'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
